"""netcheck.py: records what still works when lookups fail, renews after 15
minutes (at most hourly), and records the recovery. Network calls are faked."""
import os, struct, tempfile, unittest

import fixture as F
import netcheck as N


class Fake:
    def __init__(self, down):
        self.down = down                   # lookups fail while this is True
        self.renewals = 0

    def tools(self):
        return {"lookup": lambda: not self.down,
                "diagnose": lambda: {"router_ping": True, "internet_ping": True, "dns": {"192.168.1.1": "no answer", "1.1.1.1": "ok"}},
                "renew": self.renew, "sleep": lambda s: None}

    def renew(self):
        self.renewals += 1
        return True, "Connection successfully activated"


class Checks(unittest.TestCase):
    def setUp(self):
        self.events = tempfile.mkdtemp(prefix="iadmap-net-")

    def records(self):
        path = os.path.join(self.events, "netcheck.jsonl")
        return open(path).read().splitlines() if os.path.exists(path) else []

    def test_all_well_records_nothing(self):
        state, fake = {}, Fake(down=False)
        self.assertIsNone(N.check(state, F.NOW, fake.tools(), self.events))
        self.assertEqual(self.records(), [])

    def test_an_outage_is_diagnosed_renewed_once_an_hour_and_its_end_recorded(self):
        state, fake = {}, Fake(down=True)
        renewed = []
        for i in range(15):                                   # 75 minutes of checks, 5 minutes apart
            ev = N.check(state, F.NOW + 300 * i, fake.tools(), self.events)
            self.assertEqual(ev["kind"], "lookup_failed")
            self.assertEqual(ev["dns"]["1.1.1.1"], "ok")
            if "lookup_after_renew" in ev:
                renewed.append(ev["fails"])
        self.assertEqual(renewed, [3, 15], "after 15 minutes, then not again for an hour")
        fake.down = False
        ev = N.check(state, F.NOW + 300 * 15, fake.tools(), self.events)
        self.assertEqual(ev["kind"], "recovered")
        self.assertEqual((ev["down_min"], ev["renewals"]), (75, 2))
        self.assertEqual(state, {})
        self.assertEqual(len(self.records()), 16)

    def test_dns_question_and_verdicts(self):
        qid, packet = N.dns_query("github.com")
        self.assertIn(b"\x06github\x03com\x00", packet)
        answer = struct.pack(">HHHH", qid, 0x8180, 1, 1) + b"\0" * 4
        self.assertEqual(N.dns_verdict(qid, answer), "ok")
        self.assertEqual(N.dns_verdict(qid, struct.pack(">HHHH", qid, 0x8182, 1, 0) + b"\0" * 4), "refused (code 2)")
        self.assertEqual(N.dns_verdict(qid ^ 1, answer), "wrong reply")

    def test_resolv_conf_parsing(self):
        path = os.path.join(self.events, "resolv.conf")
        with open(path, "w") as f:
            f.write("# Generated by NetworkManager\nsearch mynetworksettings.com\nnameserver 192.168.1.1\n"
                    "nameserver 2600:4040:27d7:ef00::1\n")
        self.assertEqual(N.resolv_conf_servers(path), ["192.168.1.1", "2600:4040:27d7:ef00::1"])


if __name__ == "__main__":
    unittest.main()
